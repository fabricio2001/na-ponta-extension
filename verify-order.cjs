module.exports = async ({worker,page,assert}) => {
  await worker.evaluate(async () => chrome.storage.local.set({naPonta:{version:1,fontSize:18,responseMode:'inline',items:Array.from({length:125},(_,i)=>({id:String(i),question:`Tópico ${i+1}`,answer:`Resposta ${i+1}`}))}}));
  await page.reload(); await page.waitForFunction(()=>document.getElementById('count').textContent==='125');
  const order = () => worker.evaluate(async () => (await chrome.storage.local.get('naPonta')).naPonta.items.map(item=>item.id));
  const saved = () => page.waitForFunction(()=>document.getElementById('order-status').textContent.startsWith('Salvo:'));
  await page.locator('#filter').fill('Tópico 125');
  await page.getByRole('button',{name:'Mover para o topo: Tópico 125',exact:true}).click(); await saved();
  assert.equal((await order())[0],'124');
  await page.getByRole('button',{name:'Mover para o fim: Tópico 125',exact:true}).click(); await saved();
  assert.equal((await order()).at(-1),'124');
  await page.locator('#filter').fill('');
  await page.getByRole('button',{name:'Ordenar: Tópico 3',exact:true}).dragTo(page.locator('.library-row[data-id="0"]'),{targetPosition:{x:60,y:3}}); await saved();
  assert.deepEqual((await order()).slice(0,3),['2','0','1']);
  const target = page.locator('.library-row[data-id="1"]');
  const targetHeight = (await target.boundingBox()).height;
  await page.getByRole('button',{name:'Ordenar: Tópico 3',exact:true}).dragTo(target,{targetPosition:{x:60,y:targetHeight-8}}); await saved();
  assert.deepEqual((await order()).slice(0,3),['0','1','2']);
  // Filtering must not discard or regroup the hidden items.
  await page.locator('#filter').fill('Tópico 12');
  const filteredHandle = page.getByRole('button',{name:'Ordenar: Tópico 125',exact:true});
  await filteredHandle.scrollIntoViewIfNeeded(); const sourceBox = await filteredHandle.boundingBox();
  await page.mouse.move(sourceBox.x+8,sourceBox.y+10); await page.mouse.down();
  await page.mouse.move(sourceBox.x+18,sourceBox.y+10,{steps:4});
  const filteredTarget = page.locator('.library-row[data-id="11"]'); await filteredTarget.scrollIntoViewIfNeeded();
  const dropBox = await filteredTarget.boundingBox();
  await page.mouse.move(dropBox.x+60,dropBox.y+12,{steps:10}); await page.mouse.move(dropBox.x+61,dropBox.y+12); await page.mouse.up();
  await page.waitForFunction(()=>document.getElementById('order-status').textContent.includes('“Tópico 125” na posição 12'));
  let ids = await order(); assert.equal(ids[11],'124'); assert.equal(ids[12],'11'); assert.equal(new Set(ids).size,125);
  await page.locator('#filter').fill('');
  await page.getByRole('button',{name:'Ordenar: Tópico 125',exact:true}).focus(); await page.keyboard.press('Home'); await saved();
  assert.equal((await order())[0],'124');
  await page.keyboard.press('ArrowDown'); await saved(); assert.equal((await order())[1],'124');
  ids = await order(); await page.reload(); await page.waitForFunction(()=>document.getElementById('count').textContent==='125');
  assert.deepEqual(await order(),ids);
  assert.equal(await page.locator('.item-select').nth(1).textContent(),'Tópico 125');
  await page.getByRole('button',{name:'Tópico 125',exact:true}).click();
  await page.screenshot({path:'ordering-preview.png',fullPage:true});
  console.log('PASS: fast ordering with 125 questions, filtered top/end, real drag both directions, filtered drag, keyboard ordering and persistence.');
};
