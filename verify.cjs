const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
(async () => {
  const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'na-ponta-test-'));
  const context = await chromium.launchPersistentContext(profile, {executablePath:'C:/Program Files/BraveSoftware/Brave-Browser/Application/brave.exe', headless:true, ignoreDefaultArgs:['--disable-extensions','--disable-component-extensions-with-background-pages'], args:['--no-first-run', `--disable-extensions-except=${__dirname}`, `--load-extension=${__dirname}`]});
  try {
    const worker = context.serviceWorkers().find(w => w.url().endsWith('/background.js')) || await context.waitForEvent('serviceworker', {predicate:w=>w.url().endsWith('/background.js')});
    const origin = 'chrome-extension://' + new URL(worker.url()).host;
    const page = await context.newPage(); const errors = [];
    page.on('pageerror', error => { errors.push(error.message); console.log('PAGE ERROR',error.message); });
    page.on('console', message => console.log('CONSOLE',message.text()));
    await page.goto(origin + '/options.html');
    await page.waitForFunction(() => document.getElementById('count').textContent === '0').catch(async error => { console.log(await page.locator('body').innerText()); throw error; });
    await page.getByRole('button', {name:'＋ Nova', exact:true}).click();
    await page.locator('#question').fill('Qual é o prazo?');
    await page.locator('#answer').fill('A entrega será na sexta-feira.\nOs testes estão em andamento.');
    await page.waitForFunction(() => document.getElementById('status').textContent === 'Salvo');
    await page.reload();
    await page.getByRole('button', {name:'Qual é o prazo?',exact:true}).click();
    assert.match(await page.locator('#answer').inputValue(), /sexta-feira/);
    await page.getByRole('button', {name:'＋ Nova',exact:true}).click();
    await page.locator('#question').fill('Como está a integração?');
    await page.locator('#answer').fill('A integração está pronta.');
    await page.waitForFunction(() => document.getElementById('status').textContent === 'Salvo');
    const panel = await context.newPage(); panel.on('pageerror', error => errors.push(error.message));
    await page.getByRole('button',{name:'Mover para o fim: Como está a integração?',exact:true}).click();
    assert.equal(await page.locator('.item-select').first().textContent(),'Qual é o prazo?');
    await panel.goto(origin + '/panel.html');
    await panel.getByRole('button', {name:'Qual é o prazo?'}).click();
    assert.equal(await panel.locator('.answer:visible').count(),1);
    await panel.getByRole('button', {name:'Como está a integração?'}).click();
    assert.equal(await panel.locator('.answer:visible').count(),1);
    assert.match(await panel.locator('.answer:visible').textContent(),/integração está pronta/);
    await panel.getByRole('button', {name:'Como está a integração?'}).click();
    assert.equal(await panel.locator('.answer:visible').count(),0);
    await panel.locator('#search').fill('integracao');
    assert.equal(await panel.locator('.topic').count(),1);
    await panel.locator('#search').fill('sexta');
    assert.equal(await panel.locator('.topic').count(),1);
    for (const site of ['https://teams.microsoft.com', 'https://example.org', 'http://example.test']) await require('./verify-overlay.cjs')({context, worker, page, panel, assert, site});
    await page.locator('#font').selectOption('24');
    await panel.waitForFunction(() => getComputedStyle(document.documentElement).getPropertyValue('--answer-size') === '24px');
    const downloadPromise = page.waitForEvent('download'); await page.locator('#export').click();
    const download = await downloadPromise; const backup = path.join(profile,'backup.json'); await download.saveAs(backup);
    assert.equal(JSON.parse(fs.readFileSync(backup,'utf8')).items.length,2);
    await page.locator('#file').setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('{"version":7}')});
    await page.waitForFunction(() => document.getElementById('backup-status').textContent.includes('Não foi possível'));
    page.on('dialog', dialog => dialog.accept());
    await page.locator('#file').setInputFiles(backup);
    await page.waitForFunction(() => document.getElementById('backup-status').textContent.includes('sucesso'));
    await page.getByRole('button',{name:'Qual é o prazo?',exact:true}).click();
    await page.locator('#delete').click();
    await page.waitForFunction(() => document.getElementById('count').textContent === '1');
    const second = await context.newPage(); await second.goto(origin + '/options.html');
    await second.getByText('Configurações já abertas',{exact:true}).waitFor(); await second.close();
    await require('./verify-order.cjs')({worker,page,assert});
    await worker.evaluate(async () => { const items = Array.from({length:5000},(_,i)=>({id:String(i),question:`Pergunta ${i}`,answer:`Resposta ${i}`})); await chrome.storage.local.set({naPonta:{version:1,fontSize:18,items}}); });
    await panel.locator('#search').fill('');
    await panel.waitForFunction(() => document.querySelector('#count').textContent === '5000 perguntas');
    assert.equal(await panel.locator('.topic').count(),60);
    await panel.locator('#more').click(); assert.equal(await panel.locator('.topic').count(),120);
    await panel.locator('#search').fill('4999'); assert.equal(await panel.locator('.topic').count(),1);
    await panel.setViewportSize({width:380,height:800});
    await panel.locator('#search').fill('');
    await panel.getByRole('button',{name:'Pergunta 0',exact:true}).click();
    await panel.screenshot({path:'panel-preview.png'});
    await page.screenshot({path:'settings-preview.png',fullPage:true});
    assert.deepEqual(errors,[]);
    console.log('PASS: Brave extension loaded, persistence, accordion, search, in-page overlay transparency/drag/centering/reuse/Escape/close/navigation and no separate window, live font size, backup export/import, invalid backup, deletion, editor lock, 5000 questions and pagination.');
  } finally { await context.close(); }
})().catch(error => { console.error(error); process.exitCode=1; });
